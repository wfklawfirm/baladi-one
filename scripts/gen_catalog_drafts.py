#!/usr/bin/env python3
"""Generate supabase/migrations/0008_catalog_drafts.sql from data/catalog_draft_slim.json.
Citizen-facing transactions only, status=draft (never public until approved). No fees/amounts."""
import json, re, sys
src, out = sys.argv[1], sys.argv[2]
cat = json.load(open(src))["catalog"]
AMOUNT = re.compile(r"ل\.ل|رسم مقطوع|مليون|\d[\d,\.]*\s*(ليرة|دولار|%)")
def category(c):
    if "شكاو" in c or "مخالفات" in c: return "reports"
    if any(k in c for k in ("اقتصاد","مهنية")): return "shops"
    if any(k in c for k in ("بناء","البناء","رخص","تراخيص","إشغال","تنظيم","التنظيم","تخطيط","التخطيط")): return "licenses"
    if any(k in c for k in ("أملاك","الأملاك","بنية","سير","بيئة","نظافة","سلامة","فنية","الفنية","مشاع","الأشغال","الأراضي")): return "public_works"
    return "certificates"
def q(s): 
    assert "$q$" not in s
    return "$q$" + s + "$q$"
def items(xs):
    seen, o = set(), []
    for x in xs:
        t = (x.get("t") if isinstance(x, dict) else str(x) or "").strip()
        if t and t not in seen and not AMOUNT.search(t): seen.add(t); o.append({"ar": t})
    return o
rows = [x for x in cat if x["audience"] == "citizen"]
sql = ["-- Catalog drafts (citizen transactions). status=draft: invisible to the public until approved via review_service_version.",
       "-- Generated by scripts/gen_catalog_drafts.py. No fees/amounts. Content is unverified and needs legal review."]
dropped = 0
for i, x in enumerate(rows, 1):
    slug = x["id"].lower()
    scope = "MUNICIPAL" if "البلدية" in (x.get("authority") or "") else "SHARED"
    tl = []
    for t in x.get("timeline", []):
        v = (t.get("value") or "").strip()
        if v and v not in tl and not AMOUNT.search(v): tl.append(v)
    basis = [b.strip() for b in (x.get("legal_basis") or "").split("|") if b.strip()]
    summ = f"الفئة: {x['category']}." + (f" الأساس القانوني: {' | '.join(basis)}." if basis else "")
    if AMOUNT.search(summ): dropped += 1; summ = f"الفئة: {x['category']}."
    sql.append(f"insert into municipal_service (slug,category,scope,online_enabled,sort_order) values ({q(slug)},{q(category(x['category']))},'{scope}',false,{i*10}) on conflict (slug) do nothing;")
    sql.append("insert into service_version (service_id,version_no,status,title_ar,summary_ar,documents,steps,authority_ar,fees,processing_time_ar) "
               f"select id,1,'draft',{q(x['title'])},{q(summ)},{q(json.dumps(items(x.get('documents',[])),ensure_ascii=False))}::jsonb,{q(json.dumps(items(x.get('stages',[])),ensure_ascii=False))}::jsonb,{q(x.get('authority') or '')},null,{q(' / '.join(tl[:3])) if tl else 'null'} "
               f"from municipal_service where slug={q(slug)} on conflict (service_id,version_no) do nothing;")
    sql.append("insert into service_source (version_id,title,kind) select v.id,$q$كتالوج BALADI ONE — مسودة قيد المراجعة القانونية$q$,'internal' from service_version v join municipal_service s on s.id=v.service_id "
               f"where s.slug={q(slug)} and v.version_no=1 and not exists (select 1 from service_source z where z.version_id=v.id and z.kind='internal');")
    for b in basis[:4]:
        sql.append(f"insert into service_source (version_id,title,kind) select v.id,{q(b)},'law' from service_version v join municipal_service s on s.id=v.service_id where s.slug={q(slug)} and v.version_no=1 and not exists (select 1 from service_source z where z.version_id=v.id and z.title={q(b)});")
open(out, "w").write("\n".join(sql) + "\n")
print(len(rows), "services;", len("\n".join(sql)) // 1024, "KB; summaries scrubbed:", dropped)
